export type EiaTokenName = (typeof eiaTokenNames)[number];
export const eiaCssVar = (name: EiaTokenName) => `var(${name})`;
export function readEiaTokens(element: Element): Record<EiaTokenName, string> {
  const styles = getComputedStyle(element);
  return Object.fromEntries(
    eiaTokenNames.map((name) => [name, styles.getPropertyValue(name).trim()]),
  ) as Record<EiaTokenName, string>;
}
export function createEiaThemeOverride(
  values: Partial<Record<EiaTokenName, string>>,
): CSSProperties {
  return Object.fromEntries(
    Object.entries(values).filter(([name]) =>
      eiaTokenNames.includes(name as EiaTokenName),
    ),
  ) as CSSProperties;
}
